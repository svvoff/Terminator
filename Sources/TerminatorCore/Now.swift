import Foundation

/// Текущий момент, переданный редьюсеру параметром.
///
/// Ядро не читает часы: единственный способ узнать «который час» — этот тип на входе
/// `handle(_:at:)`. Поэтому каждый сценарий движка проверяется юнит-тестом без реальных
/// часов, без sleep и без async (findings §13).
///
/// Поле ровно одно и называется `wall` — момент на шкале **стенных часов**, той самой, на
/// которой уже живут `p_starttime` и `Rule.enabledAt` (DEC-001). Дедлайн считается и
/// сравнивается только на ней.
///
/// TASK-007 добавит сюда второе, **отдельно названное** поле suspending-семьи для накопления
/// фокуса. Дедлайна оно не касается никогда: suspending-часы останавливаются во сне системы,
/// и на машине автора две семьи разошлись на 42 часа (findings §9).
public struct Now: Equatable, Sendable {

    /// Момент на шкале стенных часов.
    public let wall: Date

    public init(wall: Date) {
        self.wall = wall
    }
}
