import Foundation

/// Текущий момент, переданный редьюсеру параметром.
///
/// Ядро не читает часы: единственный способ узнать «который час» — этот тип на входе
/// `handle(_:at:)`. Поэтому каждый сценарий движка проверяется юнит-тестом без реальных
/// часов, без sleep и без async (findings §13).
///
/// Полей три, и ни у одного нет значения по умолчанию. Умолчание здесь компилируется,
/// оставляет все существующие тесты зелёными и **навсегда замораживает** соответствующее
/// чтение в проде — ровно та молчаливая потеря, ради предотвращения которой поля и разделены.
///
/// - `wall` — момент на шкале **стенных часов**, той самой, на которой уже живут
///   `p_starttime` и `Rule.enabledAt` (DEC-001). Дедлайн считается и сравнивается только на
///   ней, и она идёт во сне системы: восемь часов сна засчитываются в лимит.
/// - `awake` — момент на **suspending**-шкале (TASK-007). Она во сне стоит, и на ней
///   накапливается фокус: те же восемь часов сна дают ноль секунд фокуса. На машине автора
///   две семьи разошлись на 42 часа (findings §9). Дедлайна это чтение не касается никогда.
/// - `timeZone` — пояс, в котором считается календарный день фокуса. Приходит снаружи, а не
///   берётся из `Calendar.current`: ядро не читает окружение, а `.current` утащил бы ещё и
///   локаль вместе с чужим календарём.
public struct Now: Equatable, Sendable {

    /// Момент на шкале стенных часов.
    public let wall: Date

    /// Момент на шкале бодрствования. С `wall` не сравним и в `Date` не переводится.
    public let awake: AwakeInstant

    /// Пояс для вычисления календарного дня.
    public let timeZone: TimeZone

    public init(wall: Date, awake: AwakeInstant, timeZone: TimeZone) {
        self.wall = wall
        self.awake = awake
        self.timeZone = timeZone
    }
}
