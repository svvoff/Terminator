import Foundation

/// Всё, что движок принимает снаружи. Адаптеры переводят мир ровно в эти десять входов:
/// шесть про отсчёт и закрытие (TASK-004) и четыре про учёт фокуса (TASK-007).
public enum EngineInput: Equatable, Sendable {

    /// Набор правил заменён целиком: загружен на старте или отредактирован.
    ///
    /// Дедлайны живых сессий пересчитываются от **прежнего** якоря (смена лимита не
    /// переякоривает, DEC-001), сессии выключённых правил снимаются. Истечение здесь **не**
    /// оценивается: укоротить лимит ниже прошедшего времени — значит просрочить сессию к
    /// ближайшему тику, а не в момент правки.
    case configChanged(RuleConfig)

    /// Полный снимок запущенных процессов — сверка.
    ///
    /// Авторитетен в обе стороны и делает три вещи в одном проходе: принимает новые
    /// процессы, снимает сессии, которых в снимке нет, и оценивает дедлайны выживших ровно
    /// так же, как `.tick`. Последнее — то, чем приложение, просрочившееся во сне Mac,
    /// закрывается сразу после пробуждения.
    ///
    /// Это же **и есть** путь бутстрапа: отдельного кода принятия на старте не существует,
    /// поэтому холодный путь прогоняется каждые 30 с, а не один раз за запуск.
    case reconcile(observed: [ObservedProcess])

    /// Вставки из KVO по `runningApplications`. Только принятие: снимка здесь нет, значит
    /// снимать по нему нечего.
    case observed(insertions: [ObservedProcess])

    /// Удаление из KVO по `runningApplications`.
    ///
    /// Это **подсказка, которая может опоздать**: список отстаёт от ядра — измерено 0.52 с,
    /// 1.53 с и один раз более 19 с на одном подопытном при 16 мс на четырёх остальных
    /// (findings §4). Поэтому лестница ретраев не ждёт этого входа и ведётся по собственным
    /// дедлайнам движка, а живость перед каждой отправкой перепроверяется по ядру.
    case terminated(pid: pid_t)

    /// Периодическая оценка: дедлайны и расписание ретраев. Адаптер шлёт каждые 5 с.
    /// Тик ничего не читает из системы — это чистый вызов редьюсера.
    case tick

    /// Исход одной отправки quit.
    case quitOutcome(pid: pid_t, outcome: QuitOutcome)

    // MARK: - Учёт фокуса (TASK-007)

    /// Фронтмост-приложение сменилось. `nil` — фронтмост нет вовсе.
    ///
    /// Эмитится **системно**, для любого приложения: наблюдатель, сужённый до наблюдаемых
    /// bundle id, не увидел бы того, против кого надо закрыть текущий спан (DEC-005).
    /// Фильтрует движок.
    ///
    /// Активация приложения с `activationPolicy != .regular` **прозрачна**: она не закрывает,
    /// не рвёт и не дробит текущий спан (findings §10).
    case frontmostChanged(FrontmostApp?)

    /// Накопление фокуса остановлено, открытый спан закрыт. Причины держатся множеством:
    /// засыпание Mac поднимает сразу две.
    case focusPaused(FocusPauseReason)

    /// Парный сигнал пробуждения, разблокировки или возврата сессии. Несёт ту же причину,
    /// поэтому адаптер не может погасить паузу, которую не поднимал. Накопление возобновится,
    /// только когда снята последняя причина, и откроет **новый** спан.
    case focusResumed(FocusPauseReason)

    /// Локальный календарный день сменился. Адаптер взводит таймер на ближайшую местную
    /// полночь, перевзводит после каждого срабатывания и шлёт этот же вход на смену
    /// системного часового пояса.
    ///
    /// Ключ дня выводится из `now.wall`, а не из входа, поэтому опоздавший или потерянный
    /// `.dayRollover` исправляется ближайшим следующим начислением, а не теряет секунды.
    case dayRollover
}
