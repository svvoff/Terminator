import Foundation

/// Что происходит, когда дедлайн истёк, — сменная стратегия (DEC-003).
///
/// Шов обязателен в MVP, стратегий в MVP ровно одна. Один метод, одна реализация, ни
/// реестра, ни конфигурации, ни второй стратегии «на будущее»: cooldown и дневной бюджет —
/// это TASK-103, и они должны стать **новой стратегией за существующим швом, а не
/// переписыванием движка** (DEC-008).
///
/// Разделение обязанностей здесь ровно такое: **когда** действовать, решает движок — он
/// владеет расписанием пяти отправок и терминальным состоянием (DEC-002, «Applies to
/// TASK-004»); **что именно сделать** — решает стратегия. Единственная точка вызова —
/// `WatchEngine.attempt(...)`, и через неё проходят все пять отправок, а не только первая.
public protocol ExpiryAction: Sendable {

    /// Эффект, которым движок отвечает на истечение дедлайна этой сессии.
    func effect(for session: ProcessSession) -> Effect
}

/// Единственная реализация MVP: попросить приложение закрыться (DEC-002).
///
/// После закрытия приложение можно немедленно запустить снова, и оно получит полный свежий
/// лимит: cooldown нет, памяти о прошлой сессии нет (DEC-003).
public struct QuitImmediately: ExpiryAction {

    public init() {}

    public func effect(for session: ProcessSession) -> Effect {
        .requestQuit(session)
    }
}
