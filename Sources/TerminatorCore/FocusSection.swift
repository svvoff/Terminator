import Foundation

/// Секция «Focus» поповера: какое из трёх состояний показать и, если это сводка, какую именно.
///
/// Решений у секции два, и оба живут здесь, а не во вью: **какую свёртку сводить** и **какое
/// состояние показать**. Вью их только читает. Инициализатор — чистая функция от снимков: ни
/// часов, ни диска, ни глобалов. Момент приходит параметром, как у `FocusSummary`.
///
/// Числа секции — нижняя граница внимания, а не его мера (DEC-005): только наблюдаемые
/// приложения и только то, что Terminator успел увидеть. Секция — ambient status, как отсчёт:
/// ни уведомлений, ни бейджей (DEC-004), и ничего, что считало бы обход (DEC-006).
public enum FocusSection: Equatable, Sendable {

    /// Показывать нечего: в окне нет ни одной строки. Ни заголовка, ни заглушки.
    case hidden

    /// Файл фокуса не прочитался при старте. Вместо таблицы — одна строка.
    case unreadable

    /// Сводка записанной истории плюс накопленного этим запуском.
    case summary(FocusSummary)

    /// Выбирает состояние секции. Порядок веток значим.
    ///
    /// - `recorded` — файл фокуса, как он прочитан при старте процесса;
    /// - `accrued` — накопленное этим запуском и ещё не слитое на диск, с открытым отрезком;
    /// - `quarantine` — причина карантина хранилища фокуса, либо nil.
    public init(
        recorded: FocusRollup,
        accrued: FocusRollup,
        quarantine: FocusLoadFailure?,
        config: RuleConfig,
        now: Now
    ) {
        // Карантин — первым и при любых данных. В карантине `recorded` пуст, а каждый слив
        // отказывает, так что сводка вышла бы из одного накопленного этим запуском: тонкая,
        // но с виду настоящая неделя. Выдать частичный день за правду недели нельзя —
        // числа фокуса и так лишь нижняя граница (DEC-005), занижать её молча нельзя тем более.
        guard quarantine == nil else {
            self = .unreadable
            return
        }

        // Сумма, а не одно из двух. Файл один отстаёт до интервала слива; накопленное одно
        // теряет все прошлые запуски. `recorded.adding(accrued)` — ровно то, что запишет
        // следующий слив, поэтому секция показывает то же число, которое продукт пишет.
        let summary = FocusSummary(rollup: recorded.adding(accrued), config: config, now: now)

        // Скрыта только при нуле строк: в окне нет данных и нет включённых правил. Пустой ключ
        // дня строк не даёт — показывать было бы нечего, кроме знаменателя без таблицы.
        guard !summary.rows.isEmpty else {
            self = .hidden
            return
        }

        self = .summary(summary)
    }
}
