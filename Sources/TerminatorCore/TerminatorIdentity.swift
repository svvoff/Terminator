import Foundation

/// Идентичность самого приложения: одна захардкоженная строка на всё дерево исходников.
///
/// Значение продублировано в `Packaging/Info.plist` как `CFBundleIdentifier`, но общей
/// константы между ними нет и быть не может: plist читается системой до запуска кода.
/// Расхождение значений — ошибка сборки, которую ловит TASK-002.
///
/// Почему константа, а не значение из бандла: у голого SwiftPM-исполняемого файла
/// `infoDictionary` пуст, а идентификатор бандла равен nil (findings §7). Значит любой путь,
/// выведенный из бандла, работает в `swift build`-бинаре и ломается — или наоборот — в
/// собранном `.app`. Захардкоженная строка ведёт себя одинаково в обоих.
///
/// Из неё выводятся три вещи, и больше ничего:
///
/// - подсистема логирования (`TerminatorLog.subsystem`);
/// - имя каталога данных (`ConfigStore.defaultDataDirectory`);
/// - запрет правила на самого себя (`Rule.init`), потому что Terminator не смотрит за собой.
public enum TerminatorIdentity {

    /// Единственное вхождение строки идентификатора в `Sources/`.
    public static let bundleIdentifier = "com.svvoff.terminator"
}
