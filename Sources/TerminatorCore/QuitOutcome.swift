import Foundation

/// Чем кончилась одна попытка отправки quit. Ровно три случая (DEC-002).
public enum QuitOutcome: Equatable, Sendable {

    /// Событие **принято к доставке** — и ничего больше. Отправка идёт с `kAENoReply`,
    /// поэтому приложение, которое проигнорировало событие, показало лист сохранения или
    /// подвисло, даёт ровно этот исход и остаётся живым: измерено `noErr` за 0.007 с при
    /// живом приложении на 20-й секунде и на 6-й минуте (findings §4).
    ///
    /// Смерть приходит позже и только отдельным `.terminated(pid:)` от KVO-наблюдателя.
    case requestSent

    /// Отправки не было: процесса нет. Возвращается в обоих случаях перепроверки
    /// `p_starttime` непосредственно перед отправкой — и когда `sysctl` вернул другое время
    /// старта (pid переиспользован), и когда не вернул ничего (процесс исчез). Список
    /// `NSWorkspace.runningApplications` отстаёт от ядра до 19+ с (findings §4), поэтому
    /// «процесс есть в списке» решением быть не может, а ядро — может.
    case notRunning

    /// Система отказала со статусом.
    case refused(OSStatus)
}

extension QuitOutcome {

    /// `errAEEventNotPermitted` из `MacErrors.h`.
    ///
    /// Значение продублировано числом сознательно: символ живёт в CoreServices, а
    /// `TerminatorCore` — только Foundation (findings §13). Совпадение значения с SDK
    /// проверяет адаптер в точке, где символ доступен.
    ///
    /// Обработка этого статуса — **оборонительная**: на пути quit он не наблюдался ни разу
    /// за семнадцать отправок против пяти приложений во всех трёх состояниях согласия,
    /// включая явный запрет (findings §5, DEC-002). Политика ретраев вокруг него не
    /// строится, но если он всё же придёт — он терминален немедленно.
    public static let eventNotPermitted: OSStatus = -1743
}
